// Copies design/v2/assets ornaments + brand mark into React components (src/ui/ornaments/generated.tsx).
// Run once after the designer changes an asset: `node scripts/gen-ornaments.mjs`. The app never imports design/.
import { readFileSync, writeFileSync } from "node:fs";

const SRC = {
  Shanyraq: "design/v2/assets/ornaments/shanyraq.svg",
  KoshkarMuiz: "design/v2/assets/ornaments/koshkar-muiz.svg",
  Divider: "design/v2/assets/ornaments/divider.svg",
  Corner: "design/v2/assets/ornaments/corner.svg",
  Mark: "design/v2/assets/brand/mark.svg",
};
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

let out = `// GENERATED by scripts/gen-ornaments.mjs from design/v2/assets (copies — the app never imports design/).\n`;
out += `// Colours are currentColor; every path keeps pathLength="1" for the «drawing» animation (DESIGN_v2 §5).\n`;
out += `import type { SVGProps } from "react";\n\n`;
out += `type P = SVGProps<SVGSVGElement>;\n\n`;
for (const [name, file] of Object.entries(SRC)) {
  const svg = readFileSync(file, "utf8")
    .replace(/<\?xml[^>]*>/, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .trim();
  const open = svg.match(/<svg([^>]*)>/)[1];
  const viewBox = open.match(/viewBox="([^"]+)"/)[1];
  const rootAttrs = {};
  for (const m of open.matchAll(/(?:^|\s)([a-zA-Z-]+)="([^"]*)"/g)) {
    if (["xmlns", "viewBox", "width", "height"].includes(m[1])) continue;
    rootAttrs[camel(m[1])] = /^#[0-9a-fA-F]{3,6}$/.test(m[2]) ? "currentColor" : m[2];
  }
  let inner = svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .replace(/<title>[\s\S]*?<\/title>/g, "")
    .replace(/="#[0-9a-fA-F]{3,6}"/g, '="currentColor"')
    .replace(/\s([a-z]+-[a-z-]+)=/g, (_, a) => ` ${camel(a)}=`)
    .replace(/\n/g, " ")
    .trim();
  const attrs = Object.entries(rootAttrs)
    .map(([k, v]) => `${k}="${v}"`)
    .join(" ");
  out += `export function ${name}(props: P) {\n  return (\n    <svg viewBox="${viewBox}" ${attrs} aria-hidden="true" focusable="false" {...props}>\n      ${inner}\n    </svg>\n  );\n}\n\n`;
}
writeFileSync("src/ui/ornaments/generated.tsx", out);
console.log("src/ui/ornaments/generated.tsx written");

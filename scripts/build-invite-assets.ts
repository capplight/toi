/**
 * Ф5: the guest page uses the designer's mockups 05–07 as the source of its static decor (SVG ornaments, envelope
 * lining, arch cover, corners) and `css/invite.css`. This script extracts those static fragments into
 * `src/server/invite/assets.generated.ts` so the page renders exactly the approved artwork; dynamic data (names,
 * dates, texts) is filled in by `src/server/invite/render.ts` with escaping.
 *
 * Run after the designer changes the mockups: `pnpm tsx scripts/build-invite-assets.ts`. Never edit the output.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const DIR = resolve("design/v2/mockups");
const TEMPLATES = {
  "ak-shanyrak": { file: "05-invite-ak-shanyraq.html", body: "tpl-ak" },
  "kok-tun": { file: "06-invite-kok-tun.html", body: "tpl-kok" },
  kyzgaldak: { file: "07-invite-kyzgaldak.html", body: "tpl-kyz" },
} as const;

function between(src: string, start: string, end: string, where: string, include = false): string {
  const a = src.indexOf(start);
  if (a < 0) throw new Error(`${where}: start not found: ${start}`);
  const from = include ? a : a + start.length;
  const b = src.indexOf(end, a + start.length);
  if (b < 0) throw new Error(`${where}: end not found: ${end}`);
  return src.slice(from, include ? b + end.length : b).trim();
}

const out: Record<string, Record<string, string>> = {};
for (const [id, t] of Object.entries(TEMPLATES)) {
  const s = readFileSync(resolve(DIR, t.file), "utf8").replace(/\r\n/g, "\n");
  const w = `${t.file}`;
  out[id] = {
    bodyClass: t.body,
    themeColor: between(s, '<meta name="theme-color" content="', '"', w),
    sceneDecor: between(s, '<div class="scene-decor">', '</div>\n  <div class="scene-inner">', w),
    envBack: between(s, '<div class="env-back">', '<div class="letter">', w, false).replace(/<\/div>\s*$/, ""),
    letterOrn: between(s, '<span class="l-names">', '</div>\n      <div class="pocket">', w).replace(
      /^[^<]*<\/span>/,
      "",
    ),
    sideDecor: between(
      s,
      '<div class="side-decor l" aria-hidden="true" data-ambient>',
      '</div>\n<div class="side-decor r"',
      w,
    ),
    archCover: between(s, '<div class="arch" data-ambient>', "</div>\n      </div>\n      <h1", w),
    dividerOrn: between(s, '<div class="divider"><i class="ln"></i>', '<i class="ln"></i></div>', w),
    corner: between(s, '<svg class="corner k1"', "</svg>", w, true).replace(
      'class="corner k1"',
      'class="corner {{k}}"',
    ),
    doneOrn: between(s, '<svg class="done-orn draw"', "</svg>", w, true),
    wordmark: between(s, '<div class="wm">', "</div>", w),
  };
}

let css = readFileSync(resolve(DIR, "css/invite.css"), "utf8");
css = css.replace(/url\("\.\.\/\.\.\/assets\/fonts\/([^"]+)"\)/g, 'url("/fonts/$1")');

const banner =
  "// GENERATED by scripts/build-invite-assets.ts from design/v2/mockups/05–07 and css/invite.css — do not edit.\n";
writeFileSync(
  resolve("src/server/invite/assets.generated.ts"),
  `${banner}export const INVITE_CSS = ${JSON.stringify(css)};\n\nexport const TEMPLATE_ASSETS = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log(`invite assets: ${Object.keys(out).length} templates, css ${css.length} chars`);
